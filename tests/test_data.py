"""Data-contract tests using runtime-generated synthetic values only."""
import importlib.util
import json
from pathlib import Path
import tempfile
import unittest
import numpy as np
import pandas as pd
import torch
import xarray as xr
from phystok.data import CityData, SyntheticView, validate_split
from phystok.data._common import PACKAGE, sha256
from phystok.data.loader import FOLD_ROOT, INTERNAL_BANK, INTERNAL_TARGET, INTERNAL_TASK, SCHEMA, SPLIT
from phystok.data.rebuild import (initialize, stage_module, build_input_file_manifest,
                                  verify_local_inputs, INPUT_DIRECTORIES, INPUT_TABLES)


class DataContractTests(unittest.TestCase):
    def test_all_folds_and_city_rotation(self):
        fits={};vals={};tests={}
        for k in range(10):
            s=validate_split(json.loads((PACKAGE/f'data/metadata/folds/fold_{k}.json').read_text()))
            for key,counts in [('train_cities',fits),('validation_cities',vals),('test_cities',tests)]:
                for c in s[key]:counts[c]=counts.get(c,0)+1
        self.assertEqual(len(fits),50)
        self.assertEqual(set(fits.values()),{8})
        self.assertEqual(set(vals.values()),{1})
        self.assertEqual(set(tests.values()),{1})

    def test_metadata_initialization_idempotent_and_external_disjoint(self):
        with tempfile.TemporaryDirectory() as t:
            p=initialize(t);initialize(t)
            x=pd.read_csv(p/'05_manifests/selected_cities_v2.csv')
            y=pd.read_csv(p/'05_manifests/external_central_china_10cities_v1.csv')
            self.assertFalse(set(x.city)&set(y.city))
            self.assertNotIn('pm25_missing_rate',x)
            receipt=json.loads((p/'09_diagnostics/external_validation/central_china_external_holdout_v1/protocol_freeze/summary.json').read_text())
            self.assertIn('public local metadata',receipt['source'])

    def test_synthetic_view_development_boundary(self):
        x=torch.randn(3,72,72);y=torch.randn(3)
        v=SyntheticView(x,y)
        b=v.batch([0,2]);self.assertEqual(tuple(b['x'].shape),(2,72,72))
        self.assertEqual(tuple(b['y'].shape),(2,))
        with self.assertRaises(ValueError):SyntheticView(x,y,role='Spatial')

    def test_actual_input_binding_rejects_tampering_and_membership_changes(self):
        # Generated byte fixtures test binding mechanics, not Zarr validity.
        with tempfile.TemporaryDirectory() as t:
            root=Path(t)
            for name in INPUT_DIRECTORIES:
                p=root/name/'runtime_synthetic_chunk';p.parent.mkdir(parents=True);p.write_bytes(b'original')
            for name in INPUT_TABLES:
                p=root/name;p.parent.mkdir(parents=True);p.write_bytes(b'synthetic')
            meta=root/'05_manifests/runtime_test.json';meta.parent.mkdir(parents=True);meta.write_text('{}')
            contract={'input_files':build_input_file_manifest(root),'bound_files':{'05_manifests/runtime_test.json':sha256(meta)}}
            self.assertEqual(verify_local_inputs(root,contract)['status'],'PASS')
            cached=verify_local_inputs(root,contract)
            self.assertEqual(cached['hash_cache_hits'],0)
            self.assertEqual(cached['content_hashes_checked'],7)
            # Same-size changes must fail even with coarse filesystem timestamps.
            chunk=root/INPUT_DIRECTORIES[0]/'runtime_synthetic_chunk';chunk.write_bytes(b'modified')
            with self.assertRaises(ValueError):verify_local_inputs(root,contract)
            chunk.write_bytes(b'original');verify_local_inputs(root,contract)
            extra=root/INPUT_DIRECTORIES[0]/'unexpected_chunk';extra.write_bytes(b'new')
            with self.assertRaises(ValueError):verify_local_inputs(root,contract)
            extra.unlink();verify_local_inputs(root,contract)
            meta.write_text('{"changed":true}')
            with self.assertRaises(ValueError):verify_local_inputs(root,contract)
            with self.assertRaises(ValueError):verify_local_inputs(root,{'bound_files':{}})

    def test_feature_rolling_and_causality(self):
        m=stage_module('09_build_observed_issue_time_feature_bank.py')
        a=np.arange(40,dtype=np.float32).reshape(20,2)
        np.testing.assert_array_equal(m.shift(a,3)[3:],a[:-3])
        self.assertTrue(np.isnan(m.shift(a,3)[:3]).all())
        out=m.rolling(a,6,'mean')
        np.testing.assert_allclose(out[8],a[3:9].mean(axis=0))
        np.testing.assert_allclose(m.rolling(a,6,'std')[8],a[3:9].std(axis=0,ddof=0),rtol=1e-6)
        polluted=a.copy();polluted[12:]=999999
        np.testing.assert_allclose(m.rolling(a,6,'mean')[:12],m.rolling(polluted,6,'mean')[:12],equal_nan=True)

    def test_full_feature_schema_and_future_perturbation(self):
        m=stage_module('09_build_observed_issue_time_feature_bank.py')
        nt,nc=100,2;ts=pd.date_range('2024-02-27',periods=nt,freq='h')
        base=np.arange(nt*nc,dtype=np.float32).reshape(nt,nc)/10+20
        names=['pm25_city_mean','pm10_city_mean','co_city_mean','so2_city_mean','no2_city_mean','o3_city_mean',
               'boundary_layer_height_m','wind_speed_10m_ms','wind_shear_magnitude_850_925_ms',
               'delta_geopotential_height_850_925_m','total_precipitation_mm','surface_solar_radiation_downwards_wm2','surface_pressure_hpa']
        data={n:(('time','city'),base.copy()) for n in names}
        for n in ['wind_speed_pressure_ms','u_wind_pressure_ms','v_wind_pressure_ms','temperature_pressure_c','relative_humidity_pressure_pct']:
            data[n]=(('time','city','pressure_level_hpa'),np.stack([base,base+1],axis=-1))
        ds=xr.Dataset(data,coords={'time':ts,'local_time':('time',ts),'city':range(nc),'pressure_level_hpa':[925,850]})
        f=m.build_feature_arrays(ds)
        layout=json.loads((PACKAGE/'configs/data_contract.json').read_text())
        self.assertEqual(list(f),layout['feature_order'])
        changed=ds.copy(deep=True)
        for n in changed.data_vars:
            if n!='local_time':changed[n].values[80:]*=20
        g=m.build_feature_arrays(changed)
        for n in f:np.testing.assert_allclose(f[n][:80],g[n][:80],equal_nan=True,err_msg=n)
        self.assertEqual(len(f),72)

    def test_scoped_loader_and_cache_with_runtime_generated_zarr(self):
        """Run the actual frozen loader on a wholly synthetic temporary dataset."""
        with tempfile.TemporaryDirectory() as t:
            root=Path(t);fold=json.loads((PACKAGE/'data/metadata/folds/fold_0.json').read_text())
            cities=fold['train_cities']+fold['validation_cities']+fold['test_cities']
            layout=json.loads((PACKAGE/'configs/data_contract.json').read_text())
            T,C=120,50
            values=np.arange(T*C,dtype=np.float32).reshape(T,C)
            def store(path,a):
                path.mkdir(parents=True)
                (path/'.zarray').write_text(json.dumps({'zarr_format':2,'shape':list(a.shape),'chunks':list(a.shape),'dtype':a.dtype.str,'compressor':None,'fill_value':None,'order':'C','filters':None}))
                (path/'0.0').write_bytes(a.tobytes())
            for j,n in enumerate(layout['feature_order']):store(root/INTERNAL_BANK/n,values+j)
            store(root/INTERNAL_TARGET/'pm25_city_mean',values*2)
            schema=root/f'05_manifests/features/{SCHEMA}/feature_schema.json';schema.parent.mkdir(parents=True);schema.write_text(json.dumps({'feature_order':layout['feature_order']}))
            split=root/f'05_manifests/splits/{SPLIT}/fold_0.json';split.parent.mkdir(parents=True);split.write_text(json.dumps(fold))
            d=root/f'{FOLD_ROOT}/fold_0';d.mkdir(parents=True)
            np.savez(d/'preprocess_stats.npz',impute_median_train=np.zeros(72),transform_center=np.ones(72),transform_scale=np.full(72,2.))
            (d/'target_stats.json').write_text(json.dumps({'statistics':{'mean':2.,'std':2.}}))
            np.savez(d/'scenario_task_rows.npz',fit_task_rows=np.arange(40),validation_task_rows=np.arange(40,45),spatial_ood_final_task_rows=np.arange(45,50),temporal_ood_final_task_rows=np.array([],int),joint_ood_final_task_rows=np.array([],int))
            start=pd.Timestamp('2023-01-01');issue=start+pd.Timedelta(hours=80);target=issue+pd.Timedelta(hours=24)
            task=pd.DataFrame({'sample_id':['synthetic_'+str(i) for i in range(C)],'city_index':range(C),'city_en':cities,
                'issue_time_index':80,'target_time_index':104,'issue_time_local':issue,'target_time_local':target,
                'target_local_year':2023,'forecast_horizon_hours':24,'target_valid_benchmark':True})
            p=root/INTERNAL_TASK;p.parent.mkdir(parents=True);task.to_parquet(p,index=False)
            files=[schema,split,d/'preprocess_stats.npz',d/'target_stats.json',d/'scenario_task_rows.npz']
            layout['bound_files']={str(p.relative_to(root)):sha256(p) for p in files}
            data=CityData(root,0,contract=layout);fit=data.view('FIT');val=data.view('VAL')
            got=fit.batch([0,2]);self.assertEqual(tuple(got['x'].shape),(2,72,72))
            expected=(np.stack([values[9:81,0]+j for j in range(72)],axis=-1)-1)/2
            np.testing.assert_array_equal(got['x'][0].numpy(),expected)
            np.testing.assert_array_equal(got['y'].numpy(),(np.array([values[104,0],values[104,2]])*2-2)/2)
            data.warm_features([fit,val]);cached=fit.batch([0,2])
            torch.testing.assert_close(got['x'],cached['x'],rtol=0,atol=0)
            with self.assertRaises(ValueError):data.view('Spatial')
            with self.assertRaises(ValueError):data.view('Spatial',purpose='evaluation',frozen_identity={'fold':0,'phase':'final','transform_sha256':'wrong'})
            data.cache=None
            ev=data.view('Spatial',purpose='evaluation',frozen_identity={'fold':0,'phase':'final','transform_sha256':data.transform_hash})
            self.assertEqual(len(ev),5)
            self.assertEqual(ev.batch([0])['sample_ids'],['synthetic_45'])
            # A second dataset object after a local rebuild must not reuse a
            # path-only task DataFrame cached by the first object.
            task['sample_id']=['rebuilt_'+str(i) for i in range(C)]
            task.to_parquet(p,index=False)
            rebuilt=CityData(root,0,contract=layout)
            self.assertEqual(rebuilt.view('FIT').batch([0])['sample_ids'],['rebuilt_0'])


if __name__=='__main__':unittest.main()
